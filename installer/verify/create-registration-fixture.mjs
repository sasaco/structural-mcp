import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { isAbsolute, join, relative, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const [installation, isolatedRoot] = process.argv.slice(2);
assert(installation && isAbsolute(installation) && isolatedRoot && isAbsolute(isolatedRoot));
const installed = resolve(installation);
const scratch = resolve(isolatedRoot);
assert(relative(scratch, installed) && !relative(scratch, installed).startsWith(".."), "Installation must be below isolated root");
const codexHome = join(scratch, "codex-home");
await mkdir(codexHome, { recursive: true });
const configPath = join(codexHome, "config.toml");
const original = '# isolated lifecycle fixture: preserve exactly\r\n[mcp_servers.structural-mcp-dev]\r\ncommand = "fixture-only-never-executed.exe"\r\nargs = ["dev.js"]\r\n';
await writeFile(configPath, original, { flag: "wx" });
// Skills go to an isolated home; a foreign skill there must survive the uninstall.
const skillsHome = join(scratch, "skills-home");
const foreignSkill = join(skillsHome, ".agents", "skills", "structural-foreign-fixture", "SKILL.md");
await mkdir(join(foreignSkill, ".."), { recursive: true });
await writeFile(foreignSkill, "---\nname: structural-foreign-fixture\ndescription: not placed by the installer\n---\n", { flag: "wx" });
const { createLayout, runAction } = await import(pathToFileURL(join(installed, "launcher.mjs")));
const layout = createLayout(installed, { codexHome, dataRoot: join(scratch, "data"), allowedRoot: join(scratch, "inputs"), skillsHome });
await runAction("register-codex", layout, {}, { initialize: async () => {}, log: () => {} });
const receipt = JSON.parse(await readFile(join(installed, "codex-registration-state.json"), "utf8"));
assert.equal(receipt.configPath, configPath, "Successful registration did not remember its isolated Codex target");
assert.equal(receipt.installRoot, installed);
const skills = JSON.parse(await readFile(join(installed, "skills-install-state.json"), "utf8"));
assert(skills.entries.length > 0 && skills.entries.every((entry) => layout.skillTargets.some((target) => resolve(target) === resolve(entry.target))), "Skills were not placed in the isolated home");
const placedSkills = skills.entries.map((entry) => join(entry.target, entry.name));
const digest = bytes => createHash("sha256").update(bytes).digest("hex");
process.stdout.write(JSON.stringify({ configPath, receiptConfigPath: receipt.configPath, originalSha256: digest(original), registeredSha256: digest(await readFile(configPath)), placedSkills, foreignSkill }) + "\n");
